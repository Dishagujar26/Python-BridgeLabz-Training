q = 1
s = 2

print(q+s) # This will print the sum of q and s, which is 3 

print(q-s) # This will print the difference of q and s, which is -1 

print(q*s) # This will print the product of q and s, which is 2

print(q/s) # This will print the quotient of q and s, which is 0.5

print(q//s) # This will print the floor division of q and s, which is 0

