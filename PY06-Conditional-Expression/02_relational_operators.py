# realtion and comparison operators
# ==, !=, >, <, >=, <= 

a = 10
b = 20

print(a == b)  # False
print(a != b)  # True
print(a > b)   # False
print(a < b)   # True
print(a >= b)  # False
print(a <= b)  # True

# Relational operators, also known as comparison operators, are used to compare two values or expressions.
# They return a boolean value (True or False) based on the comparison. These operators are commonly used in conditional statements and loops to control the flow of the program.